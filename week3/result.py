# GT 시각화 함수

def draw_ground_truth(
    image_path,
    label_path,
    class_names,
):
    image = cv2.imread(str(image_path))

    if image is None:
        raise ValueError(
            f"이미지를 불러올 수 없습니다: {image_path}"
        )

    height, width = image.shape[:2]

    gt_boxes, gt_classes = load_yolo_ground_truth(
        label_path,
        width,
        height,
    )

    for box, class_id in zip(
        gt_boxes,
        gt_classes,
    ):
        x1, y1, x2, y2 = map(int, box)

        label = class_names[class_id]

        cv2.rectangle(
            image,
            (x1, y1),
            (x2, y2),
            (0, 255, 0),
            2,
        )

        font = cv2.FONT_HERSHEY_SIMPLEX
        font_scale = 0.5
        thickness = 1

        (text_width, text_height), baseline = (
            cv2.getTextSize(
                label,
                font,
                font_scale,
                thickness,
            )
        )

        text_x1 = max(x1, 0)
        text_y2 = max(
            y1,
            text_height + baseline + 6,
        )
        text_y1 = (
            text_y2
            - text_height
            - baseline
            - 6
        )
        text_x2 = min(
            text_x1 + text_width + 6,
            image.shape[1] - 1,
        )

        cv2.rectangle(
            image,
            (text_x1, text_y1),
            (text_x2, text_y2),
            (0, 255, 0),
            -1,
        )

        cv2.putText(
            image,
            label,
            (
                text_x1 + 3,
                text_y2 - baseline - 3,
            ),
            font,
            font_scale,
            (0, 0, 0),
            thickness,
            cv2.LINE_AA,
        )

    return cv2.cvtColor(
        image,
        cv2.COLOR_BGR2RGB,
    )

# 추가 개선 : 객체에 대한 confidence score를 함께 표기하는 시각화 함수

def draw_predictions(
    image_path,
    prediction_result,
    class_names,
):
    """
    YOLO 예측 결과를 이미지에 시각화한다.

    표시 정보:
    - Bounding Box
    - 클래스명
    - Confidence Score
    """
    image = cv2.imread(str(image_path))

    if image is None:
        raise ValueError(
            f"이미지를 불러올 수 없습니다: {image_path}"
        )

    if (
        prediction_result.boxes is None
        or len(prediction_result.boxes) == 0
    ):
        return cv2.cvtColor(
            image,
            cv2.COLOR_BGR2RGB,
        )

    boxes = (
        prediction_result.boxes.xyxy
        .cpu()
        .numpy()
    )

    classes = (
        prediction_result.boxes.cls
        .cpu()
        .numpy()
        .astype(int)
    )

    confidences = (
        prediction_result.boxes.conf
        .cpu()
        .numpy()
    )

    for box, class_id, confidence in zip(
        boxes,
        classes,
        confidences,
    ):
        x1, y1, x2, y2 = map(int, box)

        class_name = class_names[class_id]
        label = f"{class_name} {confidence:.2f}"

        # Bounding Box
        cv2.rectangle(
            image,
            (x1, y1),
            (x2, y2),
            (0, 255, 0),
            2,
        )

        # 텍스트 크기 계산
        font = cv2.FONT_HERSHEY_SIMPLEX
        font_scale = 0.5
        thickness = 1

        (text_width, text_height), baseline = (
            cv2.getTextSize(
                label,
                font,
                font_scale,
                thickness,
            )
        )

        # 이미지 밖으로 라벨이 넘어가지 않도록 위치 조정
        text_x1 = max(x1, 0)
        text_y2 = max(y1, text_height + baseline + 6)
        text_y1 = text_y2 - text_height - baseline - 6
        text_x2 = min(
            text_x1 + text_width + 6,
            image.shape[1] - 1,
        )

        # 텍스트 배경
        cv2.rectangle(
            image,
            (text_x1, text_y1),
            (text_x2, text_y2),
            (0, 255, 0),
            -1,
        )

        # 클래스명 + 신뢰도
        cv2.putText(
            image,
            label,
            (
                text_x1 + 3,
                text_y2 - baseline - 3,
            ),
            font,
            font_scale,
            (0, 0, 0),
            thickness,
            cv2.LINE_AA,
        )

    return cv2.cvtColor(
        image,
        cv2.COLOR_BGR2RGB,
    )

