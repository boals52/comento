# 클래스별 라벨 통계 함수
def analyze_yolo_label_distribution(
    label_directory,
    class_names,
    split_name,
):
    """
    YOLO 라벨 파일에서 클래스별 객체 수와
    Bounding Box 상대 면적을 분석한다.

    YOLO 라벨 형식:
    class_id x_center y_center width height
    """
    records = []

    label_paths = sorted(
        label_directory.glob("*.txt")
    )

    for label_path in label_paths:
        lines = label_path.read_text(
            encoding="utf-8"
        ).strip().splitlines()

        for line in lines:
            values = line.split()

            if len(values) != 5:
                continue

            class_id = int(float(values[0]))
            x_center = float(values[1])
            y_center = float(values[2])
            width = float(values[3])
            height = float(values[4])

            relative_area = width * height

            # 과제 내 상대적 분석을 위한 임시 기준
            if relative_area < 0.01:
                size_category = "small"
            elif relative_area < 0.05:
                size_category = "medium"
            else:
                size_category = "large"

            records.append(
                {
                    "split": split_name,
                    "file_name": label_path.name,
                    "class_id": class_id,
                    "class_name": class_names[class_id],
                    "bbox_width": width,
                    "bbox_height": height,
                    "relative_area": relative_area,
                    "size_category": size_category,
                }
            )

    return pd.DataFrame(records)

